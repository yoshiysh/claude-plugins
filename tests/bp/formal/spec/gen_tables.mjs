import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { authEntryTable, authStages, formalTable, gateNextTable, inspStages, recordKeys, runMachine, startChecks, stopUseRows } from './extract.mjs';

const str = (v) => `"${v}"`;
const set = (xs) => `{${xs.join(', ')}}`;
const tri = (v) => (v === '*' ? '"*"' : v ? '"T"' : '"F"');

function dedupe(ids) {
  return ids.filter((id, i) => i === 0 || ids[i - 1] !== id);
}

export function specTables() {
  const run = runMachine();
  const gate = gateNextTable();
  const formal = formalTable();
  const insp = inspStages();
  const entry = authEntryTable();
  // 記録の種類の名前を、モデルの記録の種類に写す対応（名前だけ。鍵は表から読む）。対応に無い種類はモデルが書かない。
  const RECORD_TYPES = { 'run の開始': 'start', 段の読み直し: 'reread', 段の開始と項目の列挙: 'enter', 段の終わり: 'fin', 項目の結果: 'res', 打ち切り: 'abort', 停止: 'stop' };
  const FIELD = { stage: 's', round: 'rnd', run: 'run', item: 'item' };
  const keys = recordKeys().filter((k) => k.record in RECORD_TYPES).map((k) => {
    if (!k.mapped || k.fields.some((f) => !(f in FIELD))) throw new Error(`${k.at}: 鍵をモデルの欄に写せない: ${k.cell}`);
    return `[t |-> ${str(RECORD_TYPES[k.record])}, fields |-> ${set(k.fields.map((f) => str(FIELD[f])))}]`;
  });
  if (keys.length !== Object.keys(RECORD_TYPES).length) throw new Error('記録の表に、モデルが書く記録の種類が揃っていない');
  const lines = [
    '------------------------------ MODULE SpecTables ------------------------------',
    '\\* Generated by gen_tables.mjs from docs/specifications on every check. Do not edit.',
    `RunAllowed == ${set(run.allowed.map((a) => `<<${str(a.from)}, ${str(a.event)}, ${str(a.to)}>>`))}`,
    `RunNever == ${set(run.never.map((n) => `<<${str(n.from)}, ${str(n.event)}>>`))}`,
    `RunEvents == ${set(run.events.map((e) => str(e.id)))}`,
    `AuthStageSeq == <<${dedupe(authStages().map((s) => s.id)).map(str).join(', ')}>>`,
    `GateNext == ${set(gate.rows.map((r) => `[d |-> ${str(r.decision)}, why |-> ${str(r.reason)}, lim |-> ${str(r.limit)}, next |-> ${str(r.next)}]`))}`,
    `FormalRows == ${set(formal.rows.map((r) => `[readable |-> ${tri(r.readable)}, fails |-> ${tri(r.fails)}, unrunnable |-> ${tri(r.unrunnable)}, passes |-> ${r.passes ? 'TRUE' : 'FALSE'}, cause |-> ${str(r.cause ?? 'none')}]`))}`,
    `AuthEntry == <<${entry.rows.map((r) => `[cond |-> ${str(r.cond)}, entry |-> ${str(r.entry)}]`).join(', ')}>>`,
    `AuthPreVanish == ${set(entry.preVanish.map(String))}`,
    `RecordKeys == ${set(keys)}`,
    `InspStageSeqReview == <<${insp.filter((s) => s.fns.includes('review')).map((s) => str(s.id)).join(', ')}>>`,
    `InspStageSeqAudit == <<${insp.filter((s) => s.fns.includes('audit')).map((s) => str(s.id)).join(', ')}>>`,
    `StartChecks == <<${startChecks().map((c) => `[n |-> ${c.n}, scope |-> ${str(c.scope)}, code |-> ${str(c.code)}, same |-> ${c.same ? 'TRUE' : 'FALSE'}]`).join(', ')}>>`,
    `StopUse == ${set(stopUseRows().map((r) => `[fn |-> ${str(r.fn)}, kind |-> ${str(r.kind)}, use |-> ${str(r.use)}]`))}`,
    '================================================================================',
    '',
  ];
  return lines.join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = process.argv[2];
  if (!out) {
    console.error('usage: node gen_tables.mjs OUTPUT_DIR');
    process.exit(2);
  }
  writeFileSync(path.join(out, 'SpecTables.tla'), specTables());
}
