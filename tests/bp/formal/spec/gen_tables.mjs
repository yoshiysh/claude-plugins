import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { authResumeTable, authStages, formalTable, gateNextTable, inspResumeTable, inspStages, runMachine, startChecks, stopUseRows } from './extract.mjs';

const str = (v) => `"${v}"`;
const set = (xs) => `{${xs.join(', ')}}`;
const tri = (v) => (v === '*' ? '"*"' : v ? '"T"' : '"F"');

function dedupe(ids) {
  return ids.filter((id, i) => i === 0 || ids[i - 1] !== id);
}

export function specTables() {
  const run = runMachine();
  const gate = gateNextTable();
  const formal = formalTable();
  const resume = authResumeTable();
  const insp = inspStages();
  const inspResume = inspResumeTable();
  const lines = [
    '------------------------------ MODULE SpecTables ------------------------------',
    '\\* Generated by gen_tables.mjs from docs/specifications on every check. Do not edit.',
    `RunAllowed == ${set(run.allowed.map((a) => `<<${str(a.from)}, ${str(a.event)}, ${str(a.to)}>>`))}`,
    `RunNever == ${set(run.never.map((n) => `<<${str(n.from)}, ${str(n.event)}>>`))}`,
    `RunEvents == ${set(run.events.map((e) => str(e.id)))}`,
    `AuthStageSeq == <<${dedupe(authStages().map((s) => s.id)).map(str).join(', ')}>>`,
    `GateNext == ${set(gate.rows.map((r) => `[d |-> ${str(r.decision)}, lim |-> ${str(r.limit)}, next |-> ${str(r.next)}]`))}`,
    `FormalRows == ${set(formal.rows.map((r) => `[readable |-> ${tri(r.readable)}, fails |-> ${tri(r.fails)}, unrunnable |-> ${tri(r.unrunnable)}, passes |-> ${r.passes ? 'TRUE' : 'FALSE'}, cause |-> ${str(r.cause ?? 'none')}]`))}`,
    `StopCauses == ${set(resume.causes.map(str))}`,
    `AuthResume == ${set(resume.rows.map((r) => `[kind |-> ${str(r.kind)}, limit |-> ${str(r.limit ?? 'na')}, causes |-> ${set((Array.isArray(r.cause) ? r.cause : []).map(str))}, stages |-> [create |-> ${set(r.fnStages.create.map(str))}, update |-> ${set(r.fnStages.update.map(str))}], mode |-> ${str(r.mode)}, rewrite |-> ${str(r.rewrite)}, pending |-> ${str(r.pending)}, line |-> ${r.line}]`))}`,
    `InspStageSeqReview == <<${insp.filter((s) => s.fns.includes('review')).map((s) => str(s.id)).join(', ')}>>`,
    `InspStageSeqAudit == <<${insp.filter((s) => s.fns.includes('audit')).map((s) => str(s.id)).join(', ')}>>`,
    `InspResume == ${set(inspResume.rows.map((r) => `[stages |-> ${set(r.stages.map(str))}, mode |-> ${str(r.mode)}, line |-> ${r.line}]`))}`,
    `InspResumeSeq == <<${inspResume.sequence.map(str).join(', ')}>>`,
    `StartChecks == <<${startChecks().map((c) => `[n |-> ${c.n}, scope |-> ${str(c.scope)}, code |-> ${str(c.code)}, same |-> ${c.same ? 'TRUE' : 'FALSE'}]`).join(', ')}>>`,
    `InspClosePlacement == ${inspResume.rows.some((r) => r.placement) ? 'TRUE' : 'FALSE'}`,
    `StopUse == ${set(stopUseRows().map((r) => `[fn |-> ${str(r.fn)}, kind |-> ${str(r.kind)}, use |-> ${str(r.use)}]`))}`,
    '================================================================================',
    '',
  ];
  return lines.join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = process.argv[2];
  if (!out) {
    console.error('usage: node gen_tables.mjs OUTPUT_DIR');
    process.exit(2);
  }
  writeFileSync(path.join(out, 'SpecTables.tla'), specTables());
}
